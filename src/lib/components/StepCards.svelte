<script lang="ts">
	import { getContext } from 'svelte';
	import katex from 'katex';
	import type { StepCardData, StepCardsProps } from '$lib/contracts/component-props';
	import { DEMOS_CONTEXT, type DemosContext } from '$lib/contracts/context';
	import AttentionMatrices from './steps/AttentionMatrices.svelte';
	import { clampStep, hasScheme, parseStepState } from './steps/stepState';

	let { steps, demo, initial = 0, onStep }: StepCardsProps = $props();

	const demos = getContext<DemosContext | undefined>(DEMOS_CONTEXT);

	/** Active step index; resets to `initial` when the props change. */
	let index = $derived(clampStep(initial, steps.length));

	const current = $derived<StepCardData | undefined>(steps[index]);
	const highlight = $derived(parseStepState(current?.state));
	const schemeShown = $derived(hasScheme(steps));

	/** KaTeX output is generated by the library, which escapes its own input. */
	const formulaHtml = $derived.by(() => {
		if (!current?.formula) return '';
		return katex.renderToString(current.formula, { displayMode: true, throwOnError: false });
	});

	function go(next: number) {
		const target = clampStep(next, steps.length);
		const step = steps[target];
		if (!step || target === index) return;
		index = target;
		const patch = parseStepState(step.state).demoPatch;
		if (demo && demos && Object.keys(patch).length > 0) demos.set(demo, patch);
		onStep?.(target, step);
	}

	function onKeydown(event: KeyboardEvent) {
		if (event.key === 'ArrowLeft') {
			event.preventDefault();
			go(index - 1);
		} else if (event.key === 'ArrowRight') {
			event.preventDefault();
			go(index + 1);
		}
	}
</script>

{#if current}
	<!-- svelte-ignore a11y_no_noninteractive_element_interactions a11y_no_noninteractive_tabindex -->
	<div
		class="sc"
		class:sc-solo={!schemeShown}
		role="region"
		aria-label="Пошаговые карточки"
		tabindex="0"
		onkeydown={onKeydown}
	>
		<div class="sc-card">
			<p class="sc-count">Шаг {index + 1} из {steps.length}</p>
			{#key index}
				<div class="sc-step">
					<h3 class="sc-title">{current.title}</h3>
					<p class="sc-text">{current.text}</p>
					{#if current.formula}
						<!-- eslint-disable-next-line svelte/no-at-html-tags -- KaTeX output escapes its input -->
						<div class="sc-formula">{@html formulaHtml}</div>
					{/if}
				</div>
			{/key}
			<div class="sc-nav">
				<button type="button" class="sc-btn" disabled={index === 0} onclick={() => go(index - 1)}>
					Назад
				</button>
				<div class="sc-dots">
					{#each steps as step, i (i)}
						<button
							type="button"
							class="sc-dot"
							aria-label="Шаг {i + 1}: {step.title}"
							aria-current={i === index ? 'step' : undefined}
							onclick={() => go(i)}
						></button>
					{/each}
				</div>
				<button
					type="button"
					class="sc-btn sc-btn-primary"
					disabled={index === steps.length - 1}
					onclick={() => go(index + 1)}
				>
					Далее
				</button>
			</div>
		</div>

		{#if schemeShown}
			<div class="sc-fig">
				<AttentionMatrices active={highlight.active} pill={highlight.pill} />
			</div>
		{/if}
	</div>
{/if}

